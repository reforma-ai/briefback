#!/usr/bin/env node

// src/cli.ts
import { cancel, isCancel, outro, select } from "@clack/prompts";
import { readFileSync as readFileSync3 } from "node:fs";
import { dirname as dirname3, resolve as resolve3 } from "node:path";
import { fileURLToPath } from "node:url";
import { styleText } from "node:util";

// src/project.ts
import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  writeFileSync
} from "node:fs";
import { dirname, resolve } from "node:path";
var GENERATED_MARKER = "<!-- Generated by Briefback CLI. Run `npx @reforma/briefback@latest update` to refresh. -->";
var AGENTS_POINTER = "Larger than a quick fix: follow @BRIEFBACK.md.";
var SETUP_COMPONENTS = ["skills", "workflow", "agents"];
var DOC_COMPONENTS = ["workflow", "agents"];
function generatedWorkflow(workflow) {
  return `${GENERATED_MARKER}

${workflow.trimEnd()}
`;
}
function isGeneratedWorkflow(path) {
  return existsSync(path) && readFileSync(path, "utf8").startsWith(GENERATED_MARKER);
}
function writeAtomically(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  const temporaryPath = `${path}.briefback-tmp`;
  writeFileSync(temporaryPath, contents);
  renameSync(temporaryPath, path);
}
function ensureAgentsPointer(cwd) {
  const path = resolve(cwd, "AGENTS.md");
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current.includes("@BRIEFBACK.md")) {
    return;
  }
  if (current.length === 0) {
    writeAtomically(path, `${AGENTS_POINTER}
`);
    return;
  }
  const withTrailingNewline = current.endsWith(`
`) ? current : `${current}
`;
  const withBlankLine = withTrailingNewline.endsWith(`

`) ? withTrailingNewline : `${withTrailingNewline}
`;
  writeAtomically(path, `${withBlankLine}${AGENTS_POINTER}
`);
}
function readSetupConfig(cwd) {
  const path = resolve(cwd, ".briefback/config.json");
  if (!existsSync(path)) {
    return null;
  }
  const config = JSON.parse(readFileSync(path, "utf8"));
  if (config.version !== 1 || !Array.isArray(config.components) || config.components.some((component) => !SETUP_COMPONENTS.includes(component))) {
    throw new Error(".briefback/config.json is not a valid Briefback config.");
  }
  return config;
}
function writeSetupConfig(cwd, components) {
  const config = { version: 1, components };
  writeAtomically(resolve(cwd, ".briefback/config.json"), `${JSON.stringify(config, null, 2)}
`);
}

// src/skills.ts
import { spawnSync } from "node:child_process";
import { readFileSync as readFileSync2 } from "node:fs";
import { createRequire } from "node:module";
import { dirname as dirname2, resolve as resolve2 } from "node:path";
var BRIEFBACK_SKILLS = ["briefback"];
var SKILLS_SOURCE = "reforma-ai/briefback";
var runSkills = (args) => {
  const require2 = createRequire(import.meta.url);
  const packagePath = require2.resolve("skills/package.json");
  const packageJson = JSON.parse(readFileSync2(packagePath, "utf8"));
  const relativeBin = typeof packageJson.bin === "string" ? packageJson.bin : packageJson.bin.skills;
  if (!relativeBin) {
    throw new Error("The installed skills package does not expose a skills bin.");
  }
  const result = spawnSync(process.execPath, [resolve2(dirname2(packagePath), relativeBin), ...args], { stdio: "inherit" });
  if (result.error) {
    throw result.error;
  }
  return result.status ?? 1;
};

// src/cli.ts
function finish(message, output) {
  outro(styleText("green", message), {
    output
  });
}
var packageRoot = resolve3(dirname3(fileURLToPath(import.meta.url)), "..");
var packageJson = JSON.parse(readFileSync3(resolve3(packageRoot, "package.json"), "utf8"));
function parseOptions(args, command) {
  const forwarded = [];
  for (let index = 0;index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--agent" || argument === "-a") {
      if (command !== "init") {
        throw new Error(`${argument} is only supported by init.`);
      }
      const agent = args[index + 1];
      if (!agent || agent.startsWith("-")) {
        throw new Error(`${argument} requires an agent name.`);
      }
      forwarded.push(argument, agent);
      index += 1;
      continue;
    }
    if (argument === "--global" || argument === "-g") {
      forwarded.push(argument);
      continue;
    }
    if (argument === "--project" || argument === "-p") {
      if (command !== "update") {
        throw new Error(`${argument} is only supported by update.`);
      }
      forwarded.push(argument);
      continue;
    }
    if (argument === "--yes" || argument === "-y") {
      forwarded.push(argument);
      continue;
    }
    throw new Error(`Unknown option: ${argument}`);
  }
  return forwarded;
}
function help() {
  return `Briefback ${packageJson.version}

Usage:
  briefback init [--agent <name>] [--global] [--yes]
  briefback update [--global | --project] [--yes]
  briefback --version

Commands:
  init      Install the Briefback skill, then optionally the docs
  update    Update Briefback, installing it first when needed

The skills CLI handles agent, scope, and installation choices.
`;
}
async function promptDocs() {
  const selected = await select({
    message: "Set up Briefback docs?",
    options: [
      {
        value: true,
        label: "Yes",
        hint: "BRIEFBACK.md + pointer to it in AGENTS.md"
      },
      {
        value: false,
        label: "No",
        hint: "skill only"
      }
    ],
    initialValue: true
  });
  if (isCancel(selected)) {
    cancel("Briefback setup cancelled.");
    return null;
  }
  return selected;
}
async function runCli(args, {
  cwd = process.cwd(),
  stdout = process.stdout,
  stderr = process.stderr,
  promptDocs: selectDocs = promptDocs,
  runSkills: executeSkills = runSkills,
  workflow = readFileSync3(resolve3(packageRoot, "BRIEFBACK.md"), "utf8")
} = {}) {
  const [command, ...optionArgs] = args;
  if (!command || command === "--help" || command === "-h") {
    stdout.write(help());
    return 0;
  }
  if (command === "--version" || command === "-v") {
    stdout.write(`${packageJson.version}
`);
    return 0;
  }
  if (command !== "init" && command !== "update") {
    stderr.write(`Unknown command: ${command}

${help()}`);
    return 1;
  }
  try {
    const forwarded = parseOptions(optionArgs, command);
    const workflowPath = resolve3(cwd, "BRIEFBACK.md");
    const config = readSetupConfig(cwd);
    const legacyInstall = !config && isGeneratedWorkflow(workflowPath);
    const installing = command === "init" || !config && !legacyInstall;
    const assumeDefaults = forwarded.includes("--yes") || forwarded.includes("-y");
    let components;
    if (installing) {
      const installOptions = forwarded.filter((option) => option !== "--project" && option !== "-p");
      const status = executeSkills([
        "add",
        SKILLS_SOURCE,
        "--skill",
        ...BRIEFBACK_SKILLS,
        ...installOptions
      ]);
      if (status !== 0) {
        stderr.write(`Briefback skill install failed with exit code ${status}.
`);
        return status;
      }
      const wantDocs = assumeDefaults ? true : await selectDocs();
      if (wantDocs === null) {
        writeSetupConfig(cwd, ["skills"]);
        finish("Briefback skill installed.", stdout);
        return 0;
      }
      components = wantDocs ? ["skills", ...DOC_COMPONENTS] : ["skills"];
    } else {
      components = config?.components ?? ["skills", "workflow"];
    }
    if (!installing && components.includes("skills")) {
      const status = executeSkills([
        "update",
        ...BRIEFBACK_SKILLS,
        ...forwarded
      ]);
      if (status !== 0) {
        stderr.write(`Briefback skill update failed with exit code ${status}.
`);
        return status;
      }
    }
    if (components.includes("workflow")) {
      writeAtomically(workflowPath, generatedWorkflow(workflow));
    }
    if (components.includes("agents")) {
      ensureAgentsPointer(cwd);
    }
    writeSetupConfig(cwd, components);
    finish(installing ? "Briefback initialized." : "Briefback updated.", stdout);
    return 0;
  } catch (error) {
    stderr.write(`${error instanceof Error ? error.message : String(error)}
`);
    return 1;
  }
}

// src/bin.ts
process.exitCode = await runCli(process.argv.slice(2));
